#!/usr/bin/env python3
"""Generate the plugin's C++ headers from the v3 charter (charter/harmonia_v3.json).

- HarmoniaCharterV3.h: plain C++17 table of every parameter (range, curve, default, choices, labels, v2
  upgrade rule) and the normalization functions, identical to src/charter_v3.py; no JUCE dependency.
- HarmoniaParametersV3.h: the JUCE AudioProcessorValueTreeState layout built from that table (one group per
  module, one per DX7 operator) and the v2 state upgrade.

    python scripts/v3/charter_cpp.py                       # -> charter/generated/
    python scripts/v3/charter_cpp.py --out ../../Harmonia-APP/src/parameters
    python scripts/v3/charter_cpp.py --check               # fails if charter/generated/ is out of date
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Dict, List, Tuple

BASE_DIR = Path(__file__).resolve().parents[2]
if str(BASE_DIR) not in sys.path:
    sys.path.append(str(BASE_DIR))

from src import charter_v3  # noqa: E402

OUT = BASE_DIR / "charter" / "generated"
TABLE = "HarmoniaCharterV3.h"
LAYOUT = "HarmoniaParametersV3.h"
ENGINE = {"global": "Global", "analog": "Analog", "dx7": "Dx7"}
KIND = {"float": "Float", "int": "Int", "choice": "Choice", "bool": "Bool"}


def cpp_string(text: str) -> str:
    """C++ string literal; non-ASCII as octal escapes (at most 3 digits, so the next character is safe)."""
    out = []
    for byte in text.encode("utf-8"):
        char = chr(byte)
        if char in '"\\':
            out.append("\\" + char)
        elif 32 <= byte < 127:
            out.append(char)
        else:
            out.append(f"\\{byte:03o}")
    return '"' + "".join(out) + '"'


def cpp_float(value: float) -> str:
    text = repr(float(value))
    return text + "f" if ("." in text or "e" in text or "inf" in text) else text + ".0f"


def groups(charter: charter_v3.Charter) -> Tuple[List[Tuple[str, str, str]], Dict[str, str]]:
    """Display groups in order (id, label, label_fr) and the group of each parameter."""
    modules = {m["id"]: m for m in charter.raw["modules"]}
    order: List[Tuple[str, str, str]] = []
    of: Dict[str, str] = {}
    for module in charter.raw["modules"]:
        if module["id"] == "dx7_operator":
            for n in range(1, charter.raw["engines"]["dx7"]["operators"] + 1):
                order.append((f"dx7_op{n}", module["label"].format(n=n), module["label_fr"].format(n=n)))
        else:
            order.append((module["id"], module["label"], module["label_fr"]))
    for p in charter.params:
        if p.module == "dx7_operator":
            of[p.id] = p.id.split("_")[0] + "_" + p.id.split("_")[1]  # dx7_opN
        else:
            if p.module not in modules:
                raise ValueError(f"{p.id}: unknown module {p.module!r}")
            of[p.id] = p.module
    used = set(of.values())
    return [g for g in order if g[0] in used], of


def table_header(charter: charter_v3.Charter) -> str:
    params = charter.params
    group_order, group_of = groups(charter)
    v2_ids = [p.id for p in charter.engine_params("analog")[:20]]
    lines = [
        f"// Generated by HARMONIA/scripts/v3/charter_cpp.py from HARMONIA/charter/harmonia_v3.json (charter {charter.version}).",
        "// Do not edit: change the JSON and regenerate. Plain C++17, no JUCE dependency.",
        "#pragma once",
        "",
        "#include <algorithm>",
        "#include <array>",
        "#include <cmath>",
        "#include <cstddef>",
        "#include <string_view>",
        "",
        "namespace HarmoniaCharter",
        "{",
        f"    inline constexpr std::string_view version = {cpp_string(charter.version)};",
        "",
        "    enum class Engine { Global, Analog, Dx7 };",
        "    enum class Kind { Float, Int, Choice, Bool };",
        "",
        "    /** v3 value = offset + scale * v2[source] on physical values; source -1: no rule, the default is used. */",
        "    struct V2Rule",
        "    {",
        "        int source;",
        "        float scale;",
        "        float offset;",
        "    };",
        "",
        "    struct Param",
        "    {",
        "        std::string_view id;",
        "        std::string_view group;",
        "        Engine engine;",
        "        Kind kind;",
        "        float min;",
        "        float max;",
        "        float defaultValue;",
        "        float interval;  // 0 = continuous; int, choice and bool parameters step by 1",
        "        float skew;      // juce::NormalisableRange skew (1 = linear)",
        "        const std::string_view* choices;",
        "        int numChoices;",
        "        std::string_view unit;",
        "        std::string_view label;",
        "        std::string_view labelFr;",
        "        int displayOffset;  // shown value = stored value + displayOffset (DX7 algorithm, detune, transpose)",
        "        V2Rule v2;",
        "    };",
        "",
        "    struct Group",
        "    {",
        "        std::string_view id;",
        "        std::string_view label;",
        "        std::string_view labelFr;",
        "    };",
        "",
        "    namespace choices",
        "    {",
    ]
    for p in params:
        if p.choices:
            names = ", ".join(cpp_string(c) for c in p.choices)
            lines.append(f"        inline constexpr std::string_view {p.id}[] = {{ {names} }};")
    lines += ["    }", "", f"    inline constexpr std::array<Group, {len(group_order)}> groups {{{{"]
    for gid, label, label_fr in group_order:
        lines.append(f"        {{ {cpp_string(gid)}, {cpp_string(label)}, {cpp_string(label_fr)} }},")
    lines += ["    }};", "", "    /** Every parameter: the global ones, then the analog engine (the AI's vector order), then the DX7 voice. */",
              f"    inline constexpr std::array<Param, {len(params)}> params {{{{"]
    for p in params:
        rule = "{ -1, 1.0f, 0.0f }"
        if p.v2 is not None:
            rule = f"{{ {v2_ids.index(p.v2.source)}, {cpp_float(p.v2.scale)}, {cpp_float(p.v2.offset)} }}"
        choice_ref = (f"choices::{p.id}, {len(p.choices)}" if p.choices else "nullptr, 0")
        lines.append(
            f"        {{ {cpp_string(p.id)}, {cpp_string(group_of[p.id])}, Engine::{ENGINE[p.engine]}, Kind::{KIND[p.kind]}, "
            f"{cpp_float(p.min)}, {cpp_float(p.max)}, {cpp_float(p.default)}, {cpp_float(p.interval)}, {cpp_float(p.skew)}, "
            f"{choice_ref}, {cpp_string(p.unit)}, {cpp_string(p.label)}, {cpp_string(p.label_fr)}, {p.display_offset}, {rule} }},")
    analog = [i for i, p in enumerate(params) if p.engine == "analog"]
    dx7 = [i for i, p in enumerate(params) if p.engine == "dx7"]
    lines += [
        "    }};",
        "",
        f"    inline constexpr std::size_t analogBegin = {analog[0]}, analogEnd = {analog[-1] + 1};",
        f"    inline constexpr std::size_t dx7Begin = {dx7[0]}, dx7End = {dx7[-1] + 1};",
        "",
        "    /** The 20 parameters of a v2 preset or plugin state, in v2 order (V2Rule::source indexes this). */",
        f"    inline constexpr std::array<std::string_view, {len(v2_ids)}> v2Ids {{{{ {', '.join(cpp_string(i) for i in v2_ids)} }}}};",
        "",
        "    /** Legal value, rounded as JUCE's parameters do: int / choice like juce::roundToInt (halves to even),",
        "        bool like juce::AudioParameterBool (>= half the range), stepped float to the nearest step. */",
        "    inline float snap (const Param& p, float value) noexcept",
        "    {",
        "        value = std::clamp (value, p.min, p.max);",
        "        if (p.kind == Kind::Bool)",
        "            value = value - p.min >= 0.5f * (p.max - p.min) ? p.max : p.min;",
        "        else if (p.kind == Kind::Int || p.kind == Kind::Choice)",
        "            value = std::nearbyint (value);  // default rounding mode: to nearest, halves to even",
        "        else if (p.interval > 0.0f)",
        "            value = p.min + p.interval * std::floor ((value - p.min) / p.interval + 0.5f);",
        "        return std::clamp (value, p.min, p.max);",
        "    }",
        "",
        "    /** Physical value -> [0, 1], as juce::NormalisableRange::convertTo0to1. */",
        "    inline float toNormalized (const Param& p, float value) noexcept",
        "    {",
        "        const float proportion = (snap (p, value) - p.min) / (p.max - p.min);",
        "        return (p.skew != 1.0f && proportion > 0.0f) ? std::pow (proportion, p.skew) : proportion;",
        "    }",
        "",
        "    /** [0, 1] -> physical value, as juce::NormalisableRange::convertFrom0to1 then snapToLegalValue. */",
        "    inline float fromNormalized (const Param& p, float normalized) noexcept",
        "    {",
        "        float proportion = std::clamp (normalized, 0.0f, 1.0f);",
        "        if (p.skew != 1.0f && proportion > 0.0f)",
        "            proportion = std::exp (std::log (proportion) / p.skew);",
        "        return snap (p, p.min + (p.max - p.min) * proportion);",
        "    }",
        "",
        "    /** Index of a parameter in `params`, or -1. */",
        "    inline int indexOf (std::string_view id) noexcept",
        "    {",
        "        for (std::size_t i = 0; i < params.size(); ++i)",
        "            if (params[i].id == id)",
        "                return (int) i;",
        "        return -1;",
        "    }",
        "",
        "    /** Physical v3 value of an analog parameter for a v2 preset or state (20 physical values, v2 order). */",
        f"    inline float upgradeFromV2 (const Param& p, const std::array<float, {len(v2_ids)}>& v2Physical) noexcept",
        "    {",
        "        if (p.v2.source < 0)",
        "            return p.defaultValue;",
        "        return snap (p, p.v2.offset + p.v2.scale * v2Physical[(std::size_t) p.v2.source]);",
        "    }",
        "}",
        "",
    ]
    return "\n".join(lines)


def layout_header(charter: charter_v3.Charter) -> str:
    return f"""// Generated by HARMONIA/scripts/v3/charter_cpp.py from HARMONIA/charter/harmonia_v3.json (charter {charter.version}).
// Do not edit: change the JSON and regenerate.
#pragma once

#include <juce_audio_processors/juce_audio_processors.h>

#include "{TABLE}"

namespace HarmoniaParamsV3
{{
    inline constexpr int versionHint = 3;

    inline juce::String toJuce (std::string_view text)
    {{
        return juce::String::fromUTF8 (text.data(), (int) text.size());
    }}

    inline std::unique_ptr<juce::RangedAudioParameter> makeParameter (const HarmoniaCharter::Param& p)
    {{
        using HarmoniaCharter::Kind;
        const juce::ParameterID id {{ toJuce (p.id), versionHint }};
        const auto name = toJuce (p.label);

        switch (p.kind)
        {{
            case Kind::Float:
                return std::make_unique<juce::AudioParameterFloat> (
                    id, name, juce::NormalisableRange<float> (p.min, p.max, p.interval, p.skew), p.defaultValue,
                    juce::AudioParameterFloatAttributes().withLabel (toJuce (p.unit)));

            case Kind::Int:
            {{
                const int offset = p.displayOffset;
                return std::make_unique<juce::AudioParameterInt> (
                    id, name, (int) p.min, (int) p.max, (int) p.defaultValue,
                    juce::AudioParameterIntAttributes()
                        .withLabel (toJuce (p.unit))
                        .withStringFromValueFunction ([offset] (int value, int) {{ return juce::String (value + offset); }})
                        .withValueFromStringFunction ([offset] (const juce::String& text) {{ return text.getIntValue() - offset; }}));
            }}

            case Kind::Choice:
            {{
                juce::StringArray names;
                for (int i = 0; i < p.numChoices; ++i)
                    names.add (toJuce (p.choices[i]));
                return std::make_unique<juce::AudioParameterChoice> (id, name, names, (int) p.defaultValue);
            }}

            case Kind::Bool:
                return std::make_unique<juce::AudioParameterBool> (id, name, p.defaultValue > 0.5f);
        }}

        return nullptr;
    }}

    /** Every v3 parameter, one group per module and one per DX7 operator (in the charter's order). */
    inline juce::AudioProcessorValueTreeState::ParameterLayout createLayout()
    {{
        juce::AudioProcessorValueTreeState::ParameterLayout layout;

        for (const auto& group : HarmoniaCharter::groups)
        {{
            auto node = std::make_unique<juce::AudioProcessorParameterGroup> (toJuce (group.id), toJuce (group.label), "|");
            for (const auto& p : HarmoniaCharter::params)
                if (p.group == group.id)
                    node->addChild (makeParameter (p));
            layout.add (std::move (node));
        }}

        return layout;
    }}

    /** After loading a state saved before charter v3 (20 physical values by v2 id): analog engine, v2 rules. */
    inline void applyV2State (juce::AudioProcessorValueTreeState& apvts,
                              const std::array<float, HarmoniaCharter::v2Ids.size()>& v2Physical)
    {{
        for (const auto& p : HarmoniaCharter::params)
        {{
            if (p.engine == HarmoniaCharter::Engine::Global)
                continue;
            if (auto* parameter = apvts.getParameter (toJuce (p.id)))
            {{
                const float value = p.engine == HarmoniaCharter::Engine::Analog ? HarmoniaCharter::upgradeFromV2 (p, v2Physical)
                                                                              : p.defaultValue;
                parameter->setValueNotifyingHost (HarmoniaCharter::toNormalized (p, value));
            }}
        }}
        if (auto* engine = apvts.getParameter ("engine"))
            engine->setValueNotifyingHost (0.0f);  // analog
    }}
}}
"""


def render(charter: charter_v3.Charter) -> Dict[str, str]:
    return {TABLE: table_header(charter), LAYOUT: layout_header(charter)}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, default=OUT)
    parser.add_argument("--check", action="store_true", help="exit 1 if the files in --out differ from the charter")
    args = parser.parse_args()

    files = render(charter_v3.load())
    if args.check:
        stale = [name for name, text in files.items()
                 if not (args.out / name).exists() or (args.out / name).read_text(encoding="utf-8") != text]
        for name in stale:
            print(f"out of date: {args.out / name} (run scripts/v3/charter_cpp.py)")
        return 1 if stale else 0
    args.out.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (args.out / name).write_text(text, encoding="utf-8")
        print(args.out / name)
    return 0


if __name__ == "__main__":
    sys.exit(main())
